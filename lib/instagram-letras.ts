const MEDIA: Record<FonteMedida, number> = { anton: 0.47, bebas: 0.4, inter800: 0.7 };

/** Largura do texto em "ems" (multiplique pelo tamanho da fonte para ter pixels). */
export function larguraEmEms(
  texto: string,
  fonte: FonteMedida,
  espacamento = 0,
): number {
  const tabela = LARGURAS[fonte];
  let total = 0;
  for (const c of texto) total += (tabela[c] ?? MEDIA[fonte]) + espacamento;
  return total;
}

/** O maior tamanho de fonte em que o texto cabe na largura, até o teto. */
export function tamanhoParaCaber(
  texto: string,
  fonte: FonteMedida,
  larguraPx: number,
  teto: number,
  espacamento = 0,
): number {
  const ems = larguraEmEms(texto, fonte, espacamento);
  if (ems <= 0) return teto;
  return Math.min(teto, Math.floor(larguraPx / ems));
}

/**
 * Quebra as palavras em linhas de comprimento parecido (por largura real, não
 * por contagem de letras). `alvoEms` é a largura desejada de cada linha.
 */
export function quebrarEmLinhas<T extends { t: string }>(
  palavras: T[],
  fonte: FonteMedida,
  alvoEms: number,
): T[][] {
  const linhas: T[][] = [];
  let atual: T[] = [];
  let largura = 0;
  const espaco = larguraEmEms(" ", fonte);
  for (const p of palavras) {
    const w = larguraEmEms(p.t, fonte);
    // Passa para a linha de baixo quando a palavra ultrapassaria o alvo em mais
    // da metade dela — assim uma palavra curta não fica sozinha numa linha.
    // Fim de frase também quebra: "réplicas. O" numa linha só parte a ideia.
    const fimDeFrase = /[.!?…]["”’)]?$/.test(atual.at(-1)?.t ?? "");
    if (atual.length && (fimDeFrase || largura + espaco + w / 2 > alvoEms)) {
      linhas.push(atual);
      atual = [];
      largura = 0;
    }
    largura += (atual.length ? espaco : 0) + w;
    atual.push(p);
  }
  if (atual.length) linhas.push(atual);
  return linhas;
}

/** O texto de uma linha, como será medido e desenhado. */
export function textoDaLinha(linha: { t: string }[]): string {
  return linha.map((p) => p.t).join(" ");
}

/**
 * A largura-alvo que deixa o texto com cerca de `linhasDesejadas` linhas.
 * Nunca menor que a maior palavra: palavra não se parte.
 */
export function alvoParaLinhas(
  palavras: { t: string }[],
  fonte: FonteMedida,
  linhasDesejadas: number,
): number {
  const total = larguraEmEms(textoDaLinha(palavras), fonte);
  const maior = Math.max(0, ...palavras.map((p) => larguraEmEms(p.t, fonte)));
  return Math.max(maior, total / Math.max(1, linhasDesejadas));
}
